#!/usr/bin/env python3
"""coverage_invariant.py - every file in the working tree is recoverable, or declared not to be.

Why it exists (feedback_allowlist_scope_undercovers_by_construction, built 2026-10-29). Four
fires had one shape: a path git ignores and the private backup does not stage, so it was in
neither copy (.claude/workflows/ 08-13, frames/ 08-16, scratchpad/ 08-17, a stray settings
.bak 08-18). Each was fixed by adding one path to one list. The two lists are complements:
git covers what ships publicly, tools/backup-data.sh covers what git ignores. This checks the
complement directly, so a new path in neither is reported the day it appears.

A file is covered when it is:
  1. tracked by git, or
  2. under a path in backup-data.sh's STAGE_PATHS (read from the script itself, so the two
     cannot drift), or
  3. matched by EPHEMERAL below: caches and logs that are safe to lose, and credentials that
     are regenerated by an --auth run rather than restored from a backup. Each entry carries
     its reason. Adding to this list is the deliberate act; nothing is ephemeral by default.

Read-only: it runs `git ls-files` and reads backup-data.sh.

Usage:
  PYTHONIOENCODING=utf-8 python3 tools/coverage_invariant.py [--repo-root .] [--json]

Exit codes: 0 every file covered; 1 at least one file is in neither copy; 2 setup error
(not a git repo, or STAGE_PATHS could not be read).
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
REPO_ROOT = Path(__file__).resolve().parent.parent

# (glob, reason). fnmatch on the repo-relative path; "*" crosses "/".
EPHEMERAL = (
    ("*__pycache__/*", "bytecode cache, rebuilt on import"),
    ("*.pyc", "bytecode cache"),
    (".pytest_cache/*", "pytest cache"),
    ("*.DS_Store", "Finder metadata"),
    ("tools/launchd/logs/*", "job logs; launchd recreates them"),
    ("*.mutation_backup", "mutation_check backup, removed when its run ends"),
    ("tools/gmail_token.json", "credential; regenerated by gmail_fetch.py --auth"),
    ("tools/calendar_token.json", "credential; regenerated by calendar_fetch.py --auth"),
    ("tools/calendar_write_token.json", "credential; regenerated by calendar_write.py --auth"),
    ("tools/gmail_credentials.json", "OAuth client file; re-downloadable from Google Cloud"),
    (".env*", "secrets; never read, never backed up from here"),
)

_STAGE_RE = re.compile(r"^STAGE_PATHS=\((.*?)^\)", re.S | re.M)
_ENTRY_RE = re.compile(r'"\$WORK_TREE/([^"]+)"')


def stage_paths(backup_script: str) -> list[str]:
    m = _STAGE_RE.search(backup_script)
    if not m:
        raise ValueError("no STAGE_PATHS=( ... ) array in backup-data.sh")
    paths = _ENTRY_RE.findall(m.group(1))
    if not paths:
        raise ValueError("STAGE_PATHS is empty")
    return paths


def backed_up(rel: str, stage: list[str]) -> bool:
    for p in stage:
        if p.endswith("/"):
            if rel.startswith(p):
                return True
        elif rel == p:
            return True
    return False


def ephemeral(rel: str) -> str | None:
    for pat, why in EPHEMERAL:
        if fnmatch.fnmatch(rel, pat):
            return why
    return None


def untracked_files(root: Path) -> list[str]:
    """Every file git does not track: ignored ones and plain untracked ones."""
    out = set()
    for extra in (["--ignored"], []):
        p = subprocess.run(["git", "ls-files", "--others", "--exclude-standard", "-z", *extra],
                           cwd=str(root), capture_output=True, timeout=120)
        if p.returncode != 0:
            raise RuntimeError(p.stderr.decode(errors="replace").strip() or "git ls-files failed")
        out.update(x for x in p.stdout.decode("utf-8", errors="replace").split("\0") if x)
    return sorted(out)


def uncovered(root: Path) -> dict:
    stage = stage_paths((root / "tools" / "backup-data.sh").read_text(encoding="utf-8"))
    files = untracked_files(root)
    backed = [f for f in files if backed_up(f, stage)]
    eph = [f for f in files if not backed_up(f, stage) and ephemeral(f) is not None]
    missing = [f for f in files if not backed_up(f, stage) and ephemeral(f) is None]
    tops = sorted({f.split("/")[0] + ("/" if "/" in f else "") for f in missing})
    return {"untracked_files": len(files), "backed_up": len(backed), "ephemeral": len(eph),
            "uncovered": missing, "uncovered_count": len(missing),
            "uncovered_top_level": tops, "stage_paths": len(stage)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--repo-root", default=str(REPO_ROOT))
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    root = Path(a.repo_root).resolve()
    try:
        out = uncovered(root)
    except (OSError, ValueError, RuntimeError) as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2
    if a.json:
        print(json.dumps(out, indent=1))
    else:
        from count_report import report
        report(f"files git does not track, against {out['stage_paths']} backup paths; "
               "included = in neither copy", out["untracked_files"], out["uncovered_count"],
               {"backed up": out["backed_up"], "declared ephemeral": out["ephemeral"]})
        for f in out["uncovered"][:50]:
            print(f"  {f}")
    return 1 if out["uncovered"] else 0


if __name__ == "__main__":
    sys.exit(main())
