# WHY THIS EXISTS: until 2026-08-18 this hook was wired on `Write|Edit` only, so any
# file written through Bash -- `cat > docs/x.md <<'EOF'`, `echo ... >> README.md`,
# `tee`, `sed -i` -- reached the PUBLIC repo without ever being scanned. The gate
# read as always-on and had a hole the size of the most common way an agent writes a
# file. Found 2026-08-18 by reading the matchers in .claude/settings.json.
#
# Detection shape is deliberately INVERTED from a normal command hook. The usual
# command-hook problem (HOOK_AUTHORING.md) is a token matching where it is not
# invoked, so those hooks strip quoted spans and heredoc bodies. Here the heredoc
# body IS the payload -- it is the content about to land in a public file. So we do
# NOT strip literals: we scan the whole raw command, and gate on whether the command
# WRITES to a public path. A denylist hit plus a public write target is a leak
# regardless of which syntactic position the token sits in.
# Write targets are found by tools/shell_tokens.py, which reads the command the way
# the shell does. The regexes that used to live here (_REDIRECT_RE, _TEE_RE,
# _SED_ARGS_RE, _DD_OF_RE) each decided where an argument list ended, and a Codex
# review found a new ordinary shell form each round they were patched (2026-09-28).

# Descriptor sinks and device files: a write here never reaches the repo.
_NON_FILE_TARGETS = frozenset({"/dev/null", "/dev/stdout", "/dev/stderr", "/dev/tty", "-"})


def _unquote(tok: str) -> str:
    """Strip one pair of matching outer quotes. Kept for check_handoff_producer.py."""
    tok = tok.strip()
    if len(tok) >= 2 and tok[0] == tok[-1] and tok[0] in "\"'":
        return tok[1:-1]
    return tok




_SEGMENT_SEPARATORS = frozenset({";", "&&", "||", "\n", ";;"})
# A loop opens at its keyword, not at `do`, so a name in its CONDITION or word list
# (`while echo NAME; false; do ...; done > f`) stays with the redirect (Codex, a7d6f2a).
_COMPOUND_OPEN = frozenset({"if", "for", "while", "until", "select", "case"})
_COMPOUND_CLOSE = frozenset({"fi", "done", "esac"})
# Words after which the next word is again in command position. `time` and `!` are
# pipeline prefixes: `time if ...; fi > f` is one compound (Codex review of a7d6f2a).
_COMPOUND_PREFIX = frozenset({"then", "do", "else", "elif", "!", "{", "if", "while",
                              "until", "time"})


def split_command_segments(command: str) -> list[str]:
    """Split a shell command into independently-evaluated segments. See
    segments_with_separators, which does the work and also reports the separators."""
    return [text for text, _ in segments_with_separators(command)]


def segments_with_separators(command: str) -> list[tuple[str, frozenset[str]]]:
    """Segments of a shell command, each with the separators that precede it.

    The separators are what tell an unconditional `cd d; cmd` from a conditional
    `a && cd d; cmd` (see apply_cd).

    WHY: the first live smoke of the Bash branch (2026-08-18) FALSE-POSITIVED on a
    single compound call that wrote clean content to docs/ in step 1 and a
    denylisted token to a PRIVATE path in step 2. Scanning the command as one
    string saw "a public target exists" AND "a token exists" and blocked, though
    the token was never headed for the public file. Compound commands are the
    normal way work happens here, so that FP would have made the hook unusable and
    the predictable next step is someone disabling it.

    Splits on `;`, `&&`, `||`, `;;` and newlines. Deliberately does NOT split on a
    single `|` or `&`: in `echo BODY | tee docs/a.md` the content and its target sit
    on opposite sides of the pipe, so splitting there would hide the leak it exists
    to catch.

    A GROUP's redirect applies to the whole group, so a separator inside `{ ... }` or
    `( ... )` does NOT end the segment: splitting at the `;` in
    `{ echo TOKEN; } > docs/f.md` put the token in one segment and the public target in
    another, and the write sailed through (found 2026-08-19 by an adversarial review of
    the very segment-splitting added the day before to fix a false positive).

    Built on tools/shell_tokens.py since 2026-09-30. The hand-written scanner it
    replaced disagreed with the tokenizer on escapes (`\"` ended a string early) and on
    heredoc delimiters (`END-MARK` was not one), and each disagreement split a name
    from its public target, so the write was allowed. Separators are control-operator
    TOKENS, so nothing inside quotes, `$(...)`, backticks or a heredoc body can split.
    """
    segs: list[tuple[str, str]] = []     # (text, the separator that follows it)
    seg_start = 0
    depth = 0          # nesting of { } and ( ) groups
    compound = 0       # nesting of if/fi, do/done, case/esac
    awaiting = 0       # heredocs opened whose body has not arrived yet
    at_command_start = True
    prev_word = ""
    # Open compounds, innermost last, each with the group depth it opened at. Inside a
    # case, a `)` at the case's own depth ends a PATTERN, not a group: counting it as a
    # group close let `{ case x in a) ...;; esac; }` close the `{` at the pattern, and
    # the `;` before `}` then split the name from the group's redirect (Grok review of
    # ffe38ab, F4). An optional `(` before a pattern raises the depth, so its `)` is a
    # group-depth close and stays balanced.
    opened: list[tuple[str, int]] = []
    for t in tokenize(command):
        starts_command = at_command_start
        # `time -p if ...`: options after `time` keep the command position open.
        time_option = (starts_command and prev_word == "time" and t.kind == "word"
                       and t.text.startswith("-"))
        at_command_start = time_option or t.kind == "op" or (
            t.kind == "word" and not t.quoted and t.text in _COMPOUND_PREFIX)
        if t.kind == "word" and not time_option:
            prev_word = t.text
        # A compound command's redirect applies to its whole body, like a group's:
        # splitting at the `;` in `if a; then echo NAME; fi > docs/f.md` put the name
        # and the public target in different segments (Codex review of 68cf50a).
        # Reserved words count only unquoted and in command position (`echo if` is not
        # an if), and they get their own counter so a case pattern's `)` cannot close
        # a group.
        if t.kind == "word" and not t.quoted and starts_command:
            if t.text in _COMPOUND_OPEN:
                compound += 1
                opened.append((t.text, depth))
            elif t.text in _COMPOUND_CLOSE:
                compound = max(0, compound - 1)
                if opened:
                    opened.pop()
        pattern_end = t.kind == "op" and t.text == ")" and opened[-1:] == [("case", depth)]
        if t.kind == "op" and t.text == "(" or (t.kind == "word" and not t.quoted and t.text == "{"):
            depth += 1
        elif (t.kind == "op" and t.text == ")" and not pattern_end) or (
                t.kind == "word" and not t.quoted and t.text == "}"):
            depth = max(0, depth - 1)
        elif t.kind == "redir" and t.text.lstrip("0123456789") in ("<<", "<<-"):
            awaiting += 1
        elif t.kind == "heredoc":
            awaiting = max(0, awaiting - 1)
        # A body arrives after its line ends, so in `cat <<A > f; cat <<B > g` body A
        # comes after the `;`. Splitting there would judge it against g, not f.
        elif (t.kind == "op" and t.text in _SEGMENT_SEPARATORS and depth == 0
              and compound == 0 and awaiting == 0):
            segs.append((command[seg_start:t.start], t.text))
            seg_start = t.end
    segs.append((command[seg_start:], ""))
    # Each kept segment carries every separator since the previous kept one, so in
    # `a &&\n cd x` the cd is still seen as conditional on `a`.
    out: list[tuple[str, frozenset[str]]] = []
    before: set[str] = set()
    for text, sep_after in segs:
        if text.strip():
            out.append((text, frozenset(before)))
            before = set()
        if sep_after:
            before.add(sep_after)
    return out


_SED_SUBST_RE = re.compile(r"s([/|#,@])((?:\\.|(?!\1).)*)\1((?:\\.|(?!\1).)*)\1([gipw0-9]*)")


def strip_sed_search_sides(command: str) -> str:
    """Blank out the SEARCH half of every `s/x/y/` expression.

    A token on the search side is being DELETED from the file, not written to it, so
    scrubbing a leaked name out of a public file must not itself be blocked. The
    Write/Edit path already behaves this way -- it scans `new_string` and ignores
    `old_string` -- and until 2026-08-19 the Bash path did the opposite, so
    `sed -i '' 's/RealName/Casey Doe/' docs/f.md` (the remediation for a leak) tripped
    the gate that exists to catch the leak.

    The REPLACEMENT side is preserved and still scanned: writing a real name IN is
    exactly what must block.
    """
    return _SED_SUBST_RE.sub(lambda m: f"s{m.group(1)}{m.group(1)}{m.group(3)}{m.group(1)}{m.group(4)}", command)


def mask_heredoc_bodies(command: str) -> str:
    """Blank out heredoc BODIES so they cannot yield spurious write targets.

    A heredoc body is CONTENT, never syntax: no `>`, `tee`, `sed -i` or `dd of=` inside
    it names a file the shell will write. The body is still scanned verbatim for denylist
    tokens -- that is the entire point of the Bash branch -- because only TARGET
    EXTRACTION is masked here. `judge()` continues to receive the raw segment.

    WHY (2026-08-24; 5 fires, friction ladder said "script-patch (mandatory)" from the 3rd):
    ANY `>` inside a heredoc body was read as a redirect and the next token captured as a
    filename. Two observed surfaces, and the second is why "markdown blockquote" is too
    narrow a description of the bug:

      * a markdown blockquote line, `> **Casey:** "..."`  -> target `**Casey:**`
      * a Python comparison, `if nw >= 300:`              -> target `=300`

    Those bogus names then DEFEATED the safety net rather than being harmless. They match no
    PUBLIC_PREFIXES entry, are not under `tools/`, and contain no `/`, so `is_public_path`
    fell through to its gitignore fallback -- where `git check-ignore` exits 1 on a path that
    does not exist, which reads as "not-ignored" and therefore "public". Net effect: a write
    whose REAL target was gitignored (`/coaching/`, `/output/`) got scanned as a public
    artifact and BLOCKED.

    This invalidated the standing assumption in `extract_write_targets`' own docstring --
    "a spurious target cannot block on its own" -- which holds only while the command carries
    no denylist token. A private debrief about real people carries many.

    The fix is here rather than in `is_public_path` on purpose. Loosening the gitignore
    fallback would fail in the UNSAFE direction (a real public target misread as private);
    refusing to mine file targets out of content fails safe and removes the whole class.

    The body does not begin until after the newline ending the heredoc's own line, so
    `cat <<'EOF' > docs/x.md` keeps its redirect visible.

    Built on tools/shell_tokens.py since 2026-09-30: the tokenizer finds each body (any
    delimiter word, `<<-`, several heredocs on one line), and its span is blanked here,
    keeping newlines so line structure survives.
    """
    out = list(command)
    for t in tokenize(command):
        if t.kind == "heredoc":
            for k in range(t.start, t.end):
                if out[k] != "\n":
                    out[k] = " "
    return "".join(out)


def _parse_sed_args(words: list[str], dialect: str) -> list[str]:
    """In-place files for already-split sed words, under one dialect's rules."""
    inplace = False
    script_given = False
    operands: list[str] = []
    k = 0
    end_opts = False
    while k < len(words):
        w = words[k]
        k += 1
        if end_opts or w == "-" or not w.startswith("-"):
            operands.append(w)
            continue
        if w == "--":
            end_opts = True
            continue
        if w.startswith("--"):                  # GNU long options, which accept
            name, has_value, _ = w[2:].partition("=")   # unique abbreviations
            if name and "in-place".startswith(name):
                inplace = True
            elif name and ("expression".startswith(name)
                           or (len(name) >= 2 and "file".startswith(name))):
                script_given = True
                if not has_value:
                    k += 1
            elif name and "line-length".startswith(name) and not has_value:
                k += 1
            continue
        chars = w[1:]                           # short-option cluster
        for pos, ch in enumerate(chars):
            last = pos == len(chars) - 1
            if ch == "i" or (ch == "I" and dialect == "bsd"):
                inplace = True
                if last and k < len(words) and (dialect == "bsd" or words[k] == ""):
                    # BSD: the suffix is the next word, always. GNU: only an
                    # empty word is read as a (BSD-style) suffix, since an empty
                    # script is never what the author meant.
                    k += 1
                break                           # rest of the cluster is the suffix
            if ch in "ef":
                script_given = True
                if last:
                    k += 1
                break                           # otherwise the rest is the argument
            if ch == "l" and dialect == "gnu":
                if last:
                    k += 1
                break
    if not inplace:
        return []
    return operands if script_given else operands[1:]


def _sed_files(words: list[str]) -> list[str]:
    """Files sed edits in place, given its argument words (no redirections).

    GNU and BSD sed disagree on option arity (BSD -i/-I ALWAYS take the next word as
    the backup suffix and BSD -l is a flag; GNU -i takes no separate word and GNU -l
    takes a number), so the words are read under BOTH rule sets and the files are
    unioned, in command order. Returns [] when there is no in-place flag.

    Why a union and not a detected dialect: a command read under the wrong rules can
    lose a real file (`sed -i 's/a b/c/' a.md b.md` under BSD rules drops a.md), and a
    missed public target leaks, while a phantom one only costs a false positive.
    Accepted false positives, each blocking only when the command also carries a
    denylisted token: a BSD suffix given as its own word (`-i '.bak' 's/x/y/' f`)
    makes the expression a GNU-rules file (`-i.bak` avoids it); a GNU `-l N` makes N
    the BSD-rules script, so an attached-suffix expression becomes a BSD-rules file.
    The GNU reading also treats an empty word after -i as a suffix: not GNU arity, a
    deliberate suppression so the everyday macOS `-i ''` form produces no phantom.
    """
    found = set(_parse_sed_args(words, "bsd")) | set(_parse_sed_args(words, "gnu"))
    files: list[str] = []
    for w in words:                     # keep command order, drop duplicates
        if w in found and w not in files:
            files.append(w)
    return files


def _sed_inplace_files(argstr: str) -> list[str]:
    """_sed_files for a raw argument string (tokenized as the shell would)."""
    cmds = simple_commands(argstr)
    return _sed_files(cmds[0].words) if cmds else []


# Commands that write files, by base name, and what runs a nested command string.
_SHELLS = frozenset({"sh", "bash", "zsh", "dash", "ksh", "su"})
# Builtins that run a command string: eval (its arguments), source / . (a file, which
# is a script only when it is stdin). See scripts_run_by.
_SCRIPT_RUNNERS = frozenset({"eval", "source", "."})
_WRAPPERS = frozenset({"sudo", "env", "command", "exec", "builtin", "nice", "nohup",
                       "time", "timeout", "stdbuf", "xargs", "caffeinate", "!",
                       "then", "do", "else", "elif", "if", "while", "until", "{"})
_ASSIGNMENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\+?=")   # NAME= and NAME+=
_WRITE_REDIR = frozenset({">", ">>", ">|", "&>", "&>>", "<>"})
_EXEC_FLAGS = frozenset({"-exec", "-execdir", "-ok", "-okdir"})   # find runs the next word


_SHORT_BARE_OPTION = re.compile(r"-[A-Za-z]")


def _command_positions(words: list[str]) -> set[int]:
    """Indices of every word that could be the command the shell runs.

    The first word past assignments; and, when that word is a wrapper (sudo, env,
    timeout, xargs...), whatever the wrapper runs. Wrapper options take values in
    wrapper-specific ways, so a bare one-letter option (`-u`, `-n`) is read BOTH ways,
    as a flag and as taking the next word, and `timeout` skips its duration.

    Replaces "every word after a wrapper counts", which read `sudo echo "tee" f` as a
    write (Codex review of 6514b88), and the earlier single position, which a wrapper
    option value (`sudo -u nobody "tee" f`) hid.

    A worklist with a seen-set, not recursion: reading each bare option both ways
    forked two recursive parses per option, so `sudo -n -n ...` took exponential time
    (40 options: minutes) and 1,000 raised RecursionError (Grok review of ffe38ab, F5).
    Each (state, index) is now visited once.
    """
    out: set[int] = set()
    n = len(words)
    i = 0
    while i < n and _ASSIGNMENT.match(words[i]):
        i += 1
    # ("cmd", k, "", False): words[k] is in command position.
    # ("opt", k, wrapper, positional_seen): parse wrapper options from words[k].
    todo: list[tuple[str, int, str, bool]] = [("cmd", i, "", False)]
    seen: set[tuple[str, int, str, bool]] = set()
    while todo:
        state = todo.pop()
        if state in seen:
            continue
        seen.add(state)
        kind, k, wrapper, positional_seen = state
        if kind == "opt":
            _parse_wrapper_options(words, k, wrapper, positional_seen, todo)
        elif k < n:
            out.add(k)
            if os.path.basename(words[k]) in _WRAPPERS:
                todo.append(("opt", k + 1, os.path.basename(words[k]), False))
    return out


def _parse_wrapper_options(words: list[str], k: int, wrapper: str, positional_seen: bool,
                           todo: list[tuple[str, int, str, bool]]) -> None:
    """One step of _command_positions: read a wrapper's options from words[k] and
    queue the states that follow (a command position, or more options)."""
    n = len(words)
    while k < n:
        w = words[k]
        if w == "--":
            # Only positionals follow, and timeout's duration is still one of them
            # (`timeout -- 5 sh -c ...`, Codex review of d187aa6).
            j = k + 1
            while j < n and _ASSIGNMENT.match(words[j]):
                j += 1                  # `env -- A=1 sh -c ...` (Codex, 9a726c3)
            skip = 1 if wrapper == "timeout" and not positional_seen else 0
            todo.append(("cmd", j + skip, "", False))
            break
        if _ASSIGNMENT.match(w) or (w.startswith("-") and len(w) > 1):
            # A bare one-letter option, or a long option with no `=value`, may
            # take the next word as its value (`sudo --user nobody`); read both.
            if _SHORT_BARE_OPTION.fullmatch(w) or (w.startswith("--") and "=" not in w):
                # A flag: keep parsing options from the next word, so a wrapper
                # positional after it (timeout's duration) is still handled.
                # Marking the next word as the command skipped that duration in
                # `timeout -v 5 sh -c ...` (Codex review of 236409a).
                todo.append(("opt", k + 1, wrapper, positional_seen))
                todo.append(("opt", k + 2, wrapper, positional_seen))  # took a value
                break
            k += 1
            continue
        if wrapper == "timeout" and not positional_seen:
            todo.append(("opt", k + 1, wrapper, True))     # the duration
            break
        todo.append(("cmd", k, "", False))
        break


def _all_command_positions(words: list[str]) -> set[int]:
    """_command_positions, plus the same analysis from each word after find -exec
    (`-exec sudo sh -c ...`: the wrapper is followed there too). One helper so the
    write scan and the assignment scan can never disagree (Codex reviews of be4afb6
    and 9df3762)."""
    out = set(_command_positions(words))
    for k in range(1, len(words)):
        if words[k - 1] in _EXEC_FLAGS:
            out |= {k + p for p in _command_positions(words[k:])}
    return out


