def shell_script_variants(args: list[str]) -> list[str]:
    """The -c script a shell runs, once per positional argument bound into it.

    `sh -c 'OUT=$1; echo x > "$OUT"' _ docs/f.md`: $1, ${1}, $@ and $* are the words
    after the script, so each reference is tried with each of them. Used for both the
    write scan and the assignment scan, and by check_heredoc_quoting, so they cannot
    disagree (Codex coverage runs, 2026-10-01). [] when there is no -c script.
    """
    script = _shell_command_string(args)
    if script is None:
        return []
    k = args.index(script)
    after = args[k + 1:]            # after[0] is $0, after[N] is $N

    def bind(each: str | None) -> str:
        def sub(m: re.Match) -> str:
            ref = m.group(0).strip("${}")
            if ref in "@*":
                return each if each is not None else " ".join(after[1:])
            n = int(ref)
            return after[n] if n < len(after) else ""
        return _POSITIONAL.sub(sub, script)

    # $N binds exactly; $@ / $* are tried with each argument, since a writer like
    # `tee "$@"` takes every one as a file (Codex coverage run 2026-10-01: binding
    # every reference to the same argument never formed "$1/$2").
    if re.search(r"\$[@*]", script):
        variants = [bind(a) for a in after[1:]] or [bind(None)]
    else:
        variants = [bind(None)]
    return variants[:_MAX_CANDIDATES]


def _shell_command_string(args: list[str]) -> str | None:
    """The string a shell runs with -c, from the words after the shell's name.

    -c only says the first NON-OPTION argument is a command string, so options
    after it (`-c -e`), `--`, and options that take a value (`-o pipefail`) are
    skipped. None when there is no -c.
    """
    has_c = False
    k = 0
    while k < len(args):
        a = args[k]
        if a == "--":
            k += 1
            break
        if a in ("-o", "+o", "-O", "+O"):
            k += 2
            continue
        if len(a) > 1 and a[0] in "-+" and not a.startswith("--"):
            if a[0] == "-" and "c" in a[1:]:
                has_c = True
            k += 1
            continue
        if a.startswith("--"):
            k += 2 if a in _SHELL_LONG_WITH_VALUE else 1
            continue
        break
    if has_c and k < len(args):
        return args[k]
    return None


def _stdin_is_script(args: list[str]) -> bool:
    """True if a shell given these arguments reads its commands from stdin: no -c,
    and either -s, no script file, or the script file IS stdin (`bash /dev/stdin`).
    `bash run.sh <<EOF` hands the body to run.sh as input, so it is data."""
    if _shell_command_string(args) is not None:
        return False
    k = 0
    while k < len(args):
        a = args[k]
        if a == "--":
            k += 1
            break
        if a in ("-o", "+o", "-O", "+O"):
            k += 2
            continue
        if len(a) > 1 and a[0] in "-+" and not a.startswith("--"):
            if a[0] == "-" and "s" in a[1:]:
                return True
            k += 1
            continue
        if a.startswith("--"):
            k += 2 if a in _SHELL_LONG_WITH_VALUE else 1
            continue
        break
    return k >= len(args) or args[k] in ("/dev/stdin", "/dev/fd/0")


# Commands whose stdout is knowable from the command itself.
_PRINTERS = frozenset({"cat", "echo", "printf"})
_STDIN_REDIR = ("<<", "<<-", "<<<")


def _own_stdin(cmd) -> list[str]:
    """A command's heredoc and here-string bodies."""
    return [r.body if r.body is not None else r.target for r in cmd.redirections
            if r.op.lstrip("0123456789") in _STDIN_REDIR]


def _printed_texts(cmd) -> list[str]:
    """What a cat/echo/printf command prints: its heredoc and here-string bodies and,
    for echo/printf, its arguments (joined by space and by newline, which over-covers
    `echo` and `printf '%s\\n'`). [] for any other command."""
    words = cmd.words
    i = 0
    while i < len(words) and _ASSIGNMENT.match(words[i]):
        i += 1
    if i >= len(words) or os.path.basename(words[i]) not in _PRINTERS:
        return []
    out = _own_stdin(cmd)
    args = words[i + 1:]
    if args and os.path.basename(words[i]) != "cat":
        out += [" ".join(args), "\n".join(args)]
    return out


def _stdin_texts(cmd) -> list[str]:
    """Text on a command's stdin: its own heredoc or here-string, else what the
    command piped into it prints."""
    own = _own_stdin(cmd)
    if own:
        return own
    return _printed_texts(cmd.fed_by) if cmd.fed_by is not None else []


def _unwrap_printed(text: str) -> list[str]:
    """`$(cat <<'EOF' ... EOF)` handed to `bash -c` or eval runs what cat prints, so a
    command string that is exactly one command substitution also yields that output."""
    t = text.strip()
    if not (t.startswith("$(") and t.endswith(")")):
        return [text]
    toks = tokenize(t)
    if len(toks) != 1 or toks[0].kind != "word" or len(toks[0].subs) != 1:
        return [text]
    out = [text]
    for inner in simple_commands(toks[0].subs[0]):
        out.extend(_printed_texts(inner))
    return out


def scripts_run_by(cmd, i: int, env: dict[str, list[str]] | None) -> list[str]:
    """Every command string the shell, eval or `source` at cmd.words[i] runs.

    A -c script (each positional binding), eval's joined arguments, and, for a shell
    reading commands from stdin, the script on stdin: its heredoc or here-string, or
    the text a cat/echo/printf pipes into it. A string that is one `$(cat <<EOF)` is
    also read as what that prints. env None leaves $VAR references unexpanded.

    One helper for the write scan, the assignment scan and check_heredoc_quoting, so
    the three cannot disagree on what runs. Stdin was missing from all three: the
    tokenizer correctly hid the `>` inside `echo '... > f' | sh`, which the old regex
    had caught by accident, and nothing read the script sh would run (Grok review of
    ffe38ab, F1 and F2). `eval <<EOF` is NOT one: eval reads only its arguments.
    """
    name = os.path.basename(cmd.words[i])
    if name not in _SHELLS and name not in _SCRIPT_RUNNERS:
        return []
    rest = cmd.words[i + 1:]
    variants = expand_args(rest, env) if env is not None else [rest]
    texts: list[str] = []
    # A script on stdin is expanded like a -c string: `c='...'; echo "$c" | sh`
    # (Grok review of 88db514, F1).
    stdin = [v for t in _stdin_texts(cmd)
             for v in ((_expand_vars(t, env) or [t]) if env and "$" in t else [t])]
    if name in _SHELLS:
        for args in variants:
            texts.extend(shell_script_variants(args))
        if _stdin_is_script(rest):
            texts.extend(stdin)
    elif name == "eval":
        texts.extend(" ".join(args) for args in variants)
    elif name in ("source", ".") and rest[:1] in (["/dev/stdin"], ["/dev/fd/0"]):
        texts.extend(stdin)
    out: list[str] = []
    for t in texts:
        out.extend(_unwrap_printed(t))
    return list(dict.fromkeys(out))


def _redirect_targets(cmd) -> list[str]:
    out = []
    for r in cmd.redirections:
        core = r.op.lstrip("0123456789")
        if core in _WRITE_REDIR:
            out.append(r.target)
        elif core == ">&" and not (r.target.isdigit() or r.target == "-"):
            out.append(r.target)            # bash: `>& FILE` sends both streams to FILE
    return out


def expand_args(args: list[str], env: dict[str, list[str]]) -> list[list[str]]:
    """args with $VAR references expanded; one list per candidate value (capped).
    A command string held in a variable runs too (`c='echo x > f'; eval "$c"`), so
    eval and shell arguments are expanded before they are scanned (Codex coverage
    runs, 2026-10-01). Shared with check_heredoc_quoting."""
    out: list[list[str]] = [[]]
    for a in args:
        vals = (_expand_vars(a, env) or [a]) if "$" in a else [a]
        out = [o + [v] for o in out for v in vals][:16]
    return out


# One whole `s<d>search<d>replacement<d>flags` word, for any punctuation delimiter.
_SED_SCRIPT_WORD = re.compile(
    r"s([^\w\s\\])(?:\\.|(?!\1).)*\1(?:\\.|(?!\1).)*\1[A-Za-z0-9]*", re.S)
_FILE_EXTENSION = re.compile(r"\.\w+$")


def _is_sed_script(word: str) -> bool:
    """True if a word _sed_files returned is a substitution expression, not a file.

    _sed_files unions two dialects' readings, and its documented phantoms are all this
    shape: the expression of `sed -i '.bak' 's/a/b c/' f` is a file under GNU rules. The
    expression carries the replacement text, so the phantom target was prose, did not
    exist, read as "not ignored", and blocked an edit of a gitignored file. Neither sed
    writes to it: read as a file, it does not exist and sed stops. A path that does
    exist is kept, whatever it looks like.
    """
    return bool(_SED_SCRIPT_WORD.fullmatch(word)) and not os.path.exists(word)


def _path_shaped(word: str) -> bool:
    """Could this word be a file a GUESSED writer writes?

    Used only for a writer name found outside command position, where the hook cannot
    tell `flock lock tee docs/f.md` (a wrapper it does not know) from `--note tee up
    the call` (an argument). The words after such a name used to be reported as
    public-repo artifacts.

    A word counts if it exists as a file, has a directory part, has a file extension, or
    is a reference resolved later ($VAR, ~, a backtick). A directory is never a write
    target. What this gives up: an unknown wrapper writing a NEW top-level file with no
    extension. A writer in command position is not filtered at all.
    """
    path = os.path.expanduser(word)
    if os.path.isdir(path):
        return False
    if os.path.exists(path):
        return True
    return (any(c in word for c in "/$`") or word.startswith("~")
            or bool(_FILE_EXTENSION.search(word)))


def _writer_targets(words: list[str], quoted: list[bool],
                    env: dict[str, list[str]] | None, cmd) -> list[str]:
    """Files written by sed -i, tee and dd in one simple command, plus any command
    string handed to a shell (`bash -c "..."`, `eval "..."`).

    A word counts as the command if it sits in command position (quoted or not, so
    `"/usr/bin/sed"` counts) or appears unquoted anywhere (`find ... -exec sed -i`),
    which is what the old regexes matched. Names match on base name, so a path before
    the name does not hide it and a longer name (mysed) is not it.

    Outside command position the name may be an argument, so only path-shaped words
    after it count (see _path_shaped).
    """
    out: list[str] = []
    positions = _all_command_positions(words)
    for i, w in enumerate(words):
        in_command_position = i in positions
        if quoted[i] and not in_command_position:
            continue
        name = os.path.basename(w)
        rest = words[i + 1:]
        # A shell or eval runs its string only when the shell runs IT; the word
        # "eval" as an argument (`agent-browser eval "x=>y"`) is data.
        if (name in _SHELLS or name in _SCRIPT_RUNNERS) and not in_command_position:
            continue
        found: list[str] = []
        if name in ("sed", "gsed"):
            found = [f for f in _sed_files(rest) if not _is_sed_script(f)]
        elif name == "tee":
            end_opts = False
            for a in rest:
                if not end_opts and a == "--":
                    end_opts = True
                elif end_opts or not a.startswith("-") or a == "-":
                    found.append(a)
        elif name == "dd":
            found = [a[3:] for a in rest if a.startswith("of=")]
        else:
            for text in scripts_run_by(cmd, i, env or {}):
                out.extend(_targets_in(text, env))
        if not in_command_position:
            found = [t for t in found if _path_shaped(t)]
        out.extend(found)
    return out


# Nesting limit for command strings scanned inside command strings. Strings can GROW
# through variable expansion (`PGD=$(eval echo "$PGD")` re-expands itself), so
# recursion does not end on its own, and an uncaught RecursionError would make the
# hook fail open (found by a real-history replay, 2026-10-01).
_MAX_NESTING = 16
_nesting = [0]


def _targets_in(command: str, env: dict[str, list[str]] | None = None) -> list[str]:
    if _nesting[0] >= _MAX_NESTING:
        return []
    _nesting[0] += 1
    try:
        return _targets_in_unguarded(command, env)
    finally:
        _nesting[0] -= 1


def _targets_in_unguarded(command: str, env: dict[str, list[str]] | None = None) -> list[str]:
    targets: list[str] = []
    for cmd in simple_commands(command):
        targets.extend(_redirect_targets(cmd))
        targets.extend(_writer_targets(cmd.words, cmd.quoted, env, cmd))
        # A command substitution runs, wherever its word sits (an argument, an
        # assignment, a redirect target), so its writes count too.
        # Nesting is capped in _targets_in (see _MAX_NESTING).
        for inner in cmd.subs:
            targets.extend(_targets_in(inner, env))
    return targets


# $NAME, ${NAME}, or ${NAME<op>word} for the default/alternate operators.
_VAR_REF = re.compile(r"\$(?:\{([A-Za-z_][A-Za-z0-9_]*)(?:(:?[-=+?])([^}]*))?\}"
                      r"|([A-Za-z_][A-Za-z0-9_]*))|\$\{[^}]*\}|\$[0-9@*#?$!-]")
# Positional parameters inside a `sh -c` script: $1, ${1}, $@, $*.
_POSITIONAL = re.compile(r"\$(?:\{[0-9]+\}|[0-9@*])")
_DECLARERS = frozenset({"export", "declare", "local", "readonly", "typeset"})
# Bounds combinatorial growth only (several multi-valued variables in one word). It
# must not drop real values: at 32 it cut a for-loop's 33rd word (Codex review of
# 0a7a39a), so it is set far above any real word list.
_MAX_CANDIDATES = 1024


def _expand_vars(text: str, env: dict[str, list[str]]) -> list[str]:
    """Every value `text` could expand to, or [] if a reference cannot be resolved.

    A variable is treated as EVERY value it could hold -- each assignment seen in the
    command, its environment value, and the word of a `${X:-word}` style default --
    because the hook cannot follow the shell's control flow and assignment timing.
    "Last assignment wins" picked the private value in
    `OUT=docs/f; OUT=output/f cmd > "$OUT"` while bash wrote the public one (Codex
    review of 837e638). Over-approximating can only add a target, never drop one.
    An operator the hook does not evaluate (`${X%.md}`) leaves the text unresolved.
    """
    results = [""]
    pos = 0
    for m in _VAR_REF.finditer(text):
        literal = text[pos:m.start()]
        pos = m.end()
        name = m.group(1) or m.group(4)
        if name is None:
            return []                                   # unsupported ${...} form
        values: list[str] = list(env.get(name, []))
        if name in os.environ:
            values.append(os.environ[name])
        op, word = m.group(2), m.group(3)
        if op:
            alt = _expand_vars(word or "", env) or [word or ""]
            if op.endswith("+"):
                values = alt + [""]
            elif op.endswith("?"):
                pass
            else:
                values = values + alt
        if not values:
            return []
        results = [r + literal + v for r in results for v in dict.fromkeys(values)]
        results = results[:_MAX_CANDIDATES]
    return [r + text[pos:] for r in results]


def command_assignments(command: str) -> dict[str, list[str]]:
    if _nesting[0] >= _MAX_NESTING:
        return {}
    _nesting[0] += 1
    try:
        return _command_assignments_unguarded(command)
    finally:
        _nesting[0] -= 1


def _command_assignments_unguarded(command: str) -> dict[str, list[str]]:
    """Every value each variable is assigned anywhere in a command line.

    Collects `A=x`, `A+=x` and `export A=x` in every simple command, including those
    inside compounds (`if ...; then OUT=docs/f; fi`, missed before) and prefix
    assignments. A write target like `> "$OUT"` was skipped as unresolvable even when
    the same call set it (Codex review of a7d6f2a). See _expand_vars for why a name
    keeps all of its values.
    """
    env: dict[str, list[str]] = {}

    def merge(inner: dict[str, list[str]]) -> None:
        for name, vals in inner.items():
            env[name] = list(dict.fromkeys(env.get(name, []) + vals))[:_MAX_CANDIDATES]

    for cmd in simple_commands(command):
        words = cmd.words
        # Command strings that RUN (`bash -c`, `eval`, `$( )`) assign too, and their
        # own redirects need those values (Codex review of bd947f1).
        for inner in cmd.subs:
            merge(command_assignments(inner))
        positions = _all_command_positions(words)
        for i, w in enumerate(words):
            # Same command positions as _writer_targets, including after find -exec,
            # so a string it scans for writes is also scanned for assignments.
            if i not in positions:
                continue
            for text in scripts_run_by(cmd, i, None):     # [] unless a shell/runner
                merge(command_assignments(text))
        k = 0
        while k < len(words) and words[k] in _COMPOUND_PREFIX:
            k += 1                                      # then / do / else / time ...
        # `for NAME in w1 w2 ...` assigns each word to NAME (Codex coverage run
        # 2026-10-01, 6th: a loop variable redirect was never resolved).
        if k + 2 < len(words) and words[k] == "for" and words[k + 2] == "in":
            env.setdefault(words[k + 1], [])
            # No cap: the words are literal and already bounded by the command's
            # length; a cap dropped the 33rd item (Codex review of 19a6e71).
            env[words[k + 1]] = list(dict.fromkeys(env[words[k + 1]] + words[k + 3:]))
            continue
        declarer = k < len(words) and words[k] in _DECLARERS
        if declarer:
            k += 1
        for w in words[k:]:
            m = _ASSIGNMENT.match(w)
            if not m:
                if not declarer:
                    break           # past the leading assignments of a plain command
                continue
            name = w[:m.end()].rstrip("=").rstrip("+")
            values = _expand_vars(w[m.end():], env) or [w[m.end():]]
            values = [os.path.expanduser(v) if v.startswith("~") else v for v in values]
            if w[m.end() - 2:m.end()] == "+=":
                base = env.get(name, [""])
                values = [b + v for b in base for v in values][:_MAX_CANDIDATES]
            env.setdefault(name, [])
            env[name] = list(dict.fromkeys(env[name] + values))[:_MAX_CANDIDATES]
    return env


def extract_write_targets(command: str, env: dict[str, list[str]] | None = None) -> list[str]:
    """Paths this shell command may WRITE to.

    Covers the shapes that actually land content in a file from a command line:
    redirects (`>`, `>>`, incl. a leading fd digit), `tee`, `tee -a`, `sed -i`
    (GNU and the macOS `-i ''` form), and `dd of=`.

    KNOWN GAP, deliberately not covered: `cp` / `mv` / `rsync`. Those move bytes that
    are not present in the command string, so scanning the command text finds nothing
    to match -- extracting their destination would add target surface with no
    detection behind it. A private->public copy is caught by /audit-pii at commit
    time, not here. Documented rather than silently missing.

    Over-extraction is cheap in this hook ONLY while the command carries no denylist
    token: a spurious target cannot block on its own. That assumption failed 5 times
    between 2026-08-19 and 2026-08-24 on private writes whose CONTENT was full of real
    names, so heredoc bodies are masked below before any target is mined out of them.
    """
    # Variables: what the caller saw assigned elsewhere in the full command, then
    # anything assigned inside this text itself.
    scope: dict[str, list[str]] = {k: list(v) for k, v in (env or {}).items()}
    for k, v in command_assignments(command).items():
        scope[k] = list(dict.fromkeys(scope.get(k, []) + v))
    # Heredoc bodies are tokens, never commands, so no masking is needed here.
    targets = _targets_in(command, scope)

    expanded: list[str] = []
    for t in targets:
        if "$" in t and not t.startswith("`"):
            expanded.extend(_expand_vars(t, scope))     # [] when unresolvable: skipped
        else:
            expanded.append(t)

    out = []
    for t in expanded:
        t = t.strip()
        if not t or t in _NON_FILE_TARGETS or t.startswith("/dev/"):
            continue
        if t.startswith("`"):                         # unresolvable at hook time
            continue
        if t.startswith("~"):
            # bash expands ~ before writing; left literal, `~/x` resolved inside the
            # repo and read as a public path (replay on real history, 2026-09-30).
            t = os.path.expanduser(t)
        out.append(t)
    return out


def git_ignore_state(root: Path, rel: str) -> str:
    """'ignored' | 'tracked-or-untracked-but-not-ignored' | 'unknown'.

    Distinguishes "git says not ignored" from "git could not answer", which
    is-gitignored's bool cannot express. The fallback in is_public_path needs
    that distinction: a missing git must NOT be read as "this file is public."
    """
    try:
        r = subprocess.run(
            ["git", "-C", str(root), "check-ignore", "-q", rel],
            capture_output=True, timeout=5,
        )
    except Exception:
        return "unknown"
    if r.returncode == 0:
        return "ignored"
    if r.returncode == 1:
        return "not-ignored"
    return "unknown"          # 128 = not a repo, or any other git failure


def is_public_path(rel: str, root: Path | None = None) -> bool:
    """Does this path ship to the PUBLIC remote?

    The prefix allowlist below is a FAST PATH, not the definition. What actually
    determines public exposure is gitignore: anything git does not ignore reaches
    the public repo on the next `git add -A`.

    An allowlist under-covers by construction, and this one has now done so twice.
    2026-08-13: `.claude/workflows/` was tracked and public but absent from the tuple,
    so the always-on hook had never scanned its three .js files. 2026-08-18:
    `.claude/settings.json` (tracked, public) plus a stray `.claude/settings.json.bak`
    (untracked, NOT gitignored, and one `git add -A` from shipping) were both reported
    "not a public artifact." Each time the fix had been to append another prefix, which
    treats the symptom. The gitignore fallback below is the source fix; the tuple is
    kept only so the common case avoids a subprocess and so behaviour degrades safely
    when git cannot answer.
    """
    if rel.startswith("data/"):
        return False
    if any(rel.startswith(p) for p in PUBLIC_PREFIXES):
        return True
    if rel.startswith("tools/") and rel.rsplit(".", 1)[-1] in ("py", "md", "sh"):
        return True
    if "/" not in rel and rel.endswith(".md"):  # top-level markdown
        return True
    if root is not None and git_ignore_state(root, rel) == "not-ignored":
        return True
    return False


def is_gitignored(root: Path, rel: str) -> bool:
    """True if git ignores the path. Fails toward False (scan) when git is unavailable,
    so the public-path glob still protects the surface."""
    try:
        r = subprocess.run(
            ["git", "-C", str(root), "check-ignore", "-q", rel],
            capture_output=True, timeout=5,
        )
        return r.returncode == 0
    except Exception:
        return False


def _load_list(root: Path, rel: str) -> list[str]:
    """One token per line; blank lines and # comments skipped. A missing or unreadable
    file is an empty list (fail open), the same for every tier."""
    try:
        lines = (root / rel).read_text(encoding="utf-8").splitlines()
    except (FileNotFoundError, PermissionError):
        return []
    return [ln.strip() for ln in lines if ln.strip() and not ln.startswith("#")]


def load_denylist(root: Path) -> list[str]:
    """BLOCK-tier tokens."""
    return _load_list(root, DENYLIST_REL)


def load_ambiguous(root: Path) -> list[str]:
    """WARN-tier tokens."""
    return _load_list(root, AMBIGUOUS_REL)


def load_target_words(root: Path) -> list[str]:
    """Pipeline company names that are also ordinary English words, as written in the
    pipeline's Company column."""
    return _load_list(root, TARGET_WORDS_REL)


def repo_root() -> Path:
    """The repo root, from this file's location (tools/), not cwd(): the hook runs with
    an absolute script path, so __file__ is reliable even when the session is launched
    from outside the repo root (fable-audit 2026-07-07 #3). PII_REPO_ROOT overrides it
    for tests, which inject a fixture repo + denylist."""
    root_env = os.environ.get("PII_REPO_ROOT")
    return Path(root_env).resolve() if root_env else Path(__file__).resolve().parent.parent


_QUOTE_OPENERS = "\"'`\u201c\u2018"
_MARKUP_OPENERS = " \t*_([{" + _QUOTE_OPENERS
_LINE_MARKERS = re.compile(r"[ \t]*(?:[-+*>#|/]+[ \t]*)*(?:\d+[.)])?")
_SENTENCE_CONTINUES = re.compile(r"(?:[ \t]+|-)[a-z]")


def opens_a_sentence(before: str, after: str) -> bool:
    """Is a capitalised word at this position capitalised because it starts a sentence?

    `before` is the text on the same line ahead of the word, `after` the text behind it.
    Both halves must hold. The word is followed by a lowercase word (or a hyphenated
    lowercase suffix), so a bare name in a table cell, a list item or a quoted fixture
    string is NOT an opener. And it sits where a sentence starts: at the start of the
    line, after list, heading, quote, table or comment markers, after . ! ? : ; or
    directly after an opening quote.

    What this gives up, on purpose: a real company name that itself starts a sentence
    passes the BLOCK tier. The sweep reports those under ambiguous_hits instead.
    """
    if not _SENTENCE_CONTINUES.match(after):
        return False
    if before.rstrip("*_")[-1:] in _QUOTE_OPENERS and before.rstrip("*_"):
        return True
    bare = before.rstrip(_MARKUP_OPENERS)
    if not bare or bare[-1] in ".!?:;":
        return True
    return bool(_LINE_MARKERS.fullmatch(bare))


def find_target_words(content: str, words: list[str]) -> list[str]:
    """Target words used as a NAME somewhere in `content`: case-sensitive, whole word,
    and at least one occurrence that does not open a sentence.

    WHY A SEPARATE TIER (2026-10-12). A pipeline company whose name is an ordinary word
    could only sit on the WARN tier, which reaches nobody on the write path, because
    find_pii cannot tell an imperative verb that opens a sentence from a company
    of the same name. Measured on
    647 tracked files with the 45 live words: 12 occurrences, 7 of them sentence
    openers. Skipping openers is what makes blocking the rest affordable.
    """
    hits = []
    for word in words:
        pattern = r"(?<![\w])" + re.escape(word) + r"(?![\w])"
        for m in re.finditer(pattern, content):
            line_start = content.rfind("\n", 0, m.start()) + 1
            if not opens_a_sentence(content[line_start:m.start()], content[m.end():m.end() + 8]):
                hits.append(word)
                break
    return hits


def find_pii(content: str, tokens: list[str]) -> list[str]:
    """Case-sensitive whole-word/phrase matches. The trailing/leading \\w boundaries
    keep a short brand token from matching inside a longer word (e.g. 'Zorp' must not
    fire on 'Zorped', and a word like 'Market' must not fire on 'marketing')."""
    hits = []
    for tok in tokens:
        pattern = r"(?<![\w])" + re.escape(tok) + r"(?![\w])"
        if re.search(pattern, content):
            hits.append(tok)
    return hits


ACCEPT_FLAG = "--accept-ambiguous"


def parse_scan_args(args: list[str]):
    """Split the words after --scan into (paths, accepted, error).

    `--accept-ambiguous FILE:TOKEN` (or `=FILE:TOKEN`), repeatable, is one explicit
    verdict that TOKEN in FILE is not the company. There is no token-wide form: the
    same word is a placeholder in one file and the real company in another.
    """
    paths, accepted = [], set()
    k = 0
    while k < len(args):
        a = args[k]
        k += 1
        if a == "--stdin-paths":
            continue
        if a == ACCEPT_FLAG or a.startswith(ACCEPT_FLAG + "="):
            if a == ACCEPT_FLAG:
                value = args[k] if k < len(args) else ""
                k += 1
            else:
                value = a[len(ACCEPT_FLAG) + 1:]
            file, sep, token = value.rpartition(":")
            if not sep or not file.strip() or not token.strip():
                return [], set(), (f"{ACCEPT_FLAG} takes FILE:TOKEN, one entry of "
                                   f"ambiguous_unresolved[]; got {value!r}")
            accepted.add(f"{file.strip()}:{token.strip()}")
            continue
        paths.append(a)
    return paths, accepted, None


def scan_paths(paths: list[str], accepted=frozenset()) -> int:
    """`--scan` sweep mode: run the SAME word-boundary matcher over a list of files.

    WHY THIS EXISTS (promoted from [[feedback_replace_all_substring_check]], 3 fires).
    The hook body is only reachable by piping a synthetic Write payload per file, so
    anyone auditing a whole tree hand-rolls a `grep` instead — and hand-rolled greps use
    substring matching. On 2026-08-12 a pre-push sweep used `grep -qiF` and produced
    ~190 false hits, essentially all of them a short brand token matching INSIDE an
    unrelated common word (the shape of `Ace` firing on `placed`). `/audit-pii` Step 0b
    already said to use word boundaries; prose alone did not hold. This makes the
    correct sweep the EASY one, which is the only reliable fix.

    The false-positive cost is not just noise: a substring sweep feeding a
    `git filter-repo --replace-text` scrub corrupts unrelated content.

    Exit 2 if any denylist token is found (same contract as the hook), 1 if zero
    files were scanned or a public file could not be read, else 0 -- except:

    Exit 3 if no denylist token is found but an ambiguous-tier match has no verdict
    (added 2026-10-13). The write path prints that tier at exit 0, which reaches
    nobody; this sweep is its only reader (/audit-pii Step 1), and it used to print
    the matches at exit 0 too. `accepted` holds the FILE:TOKEN verdicts for this run.
    """
    root = repo_root()
    tokens = load_denylist(root)
    ambiguous = load_ambiguous(root)
    target_words = load_target_words(root)

    result = {"scanned": 0, "skipped": [], "unreadable": [], "hits": [],
              "ambiguous_hits": [], "ambiguous_unresolved": [],
              "denylist_tokens": len(tokens)}
    if not tokens:
        result["error"] = "denylist empty — run gen_pii_denylist.py first; a sweep with no tokens is not a pass"
        print(json.dumps(result, indent=2))
        return 2

    for raw in paths:
        try:
            rel = os.path.relpath(os.path.abspath(raw), root).replace(os.sep, "/")
        except Exception:
            result["skipped"].append({"path": raw, "why": "unresolvable"})
            continue
        if rel.startswith(".."):
            result["skipped"].append({"path": rel, "why": "outside repo"})
            continue
        if not is_public_path(rel, root):
            result["skipped"].append({"path": rel, "why": "not a public artifact"})
            continue
        if is_gitignored(root, rel):
            result["skipped"].append({"path": rel, "why": "gitignored"})
            continue
        if is_binary(rel):
            result["skipped"].append({"path": rel, "why": "binary"})
            continue
        try:
            content = (root / rel).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            # A public file that could not be read is not a skip: it ships, and it was
            # not checked. Until 2026-10-13 it sat in skipped[] beside the gitignored
            # and binary paths and the sweep still said clean.
            result["unreadable"].append({"path": rel, "why": f"{type(exc).__name__}: {exc}"})
            continue

        result["scanned"] += 1
        hits = find_pii(content, tokens) + find_target_words(content, target_words)
        if hits:
            result["hits"].append({"file": rel, "tokens": hits})
        # A target word that only ever opens a sentence here passed the block above.
        # It is still a company name in a public file as far as a matcher can tell.
        amb = find_pii(content, ambiguous) + [
            w for w in find_pii(content, target_words) if w not in hits]
        if amb:
            # Line numbers, so a verdict does not need a second search.
            lines = {t: [n for n, ln in enumerate(content.splitlines(), 1)
                         if find_pii(ln, [t])] for t in amb}
            result["ambiguous_hits"].append({"file": rel, "tokens": amb, "lines": lines})
            result["ambiguous_unresolved"] += [
                f"{rel}:{t}" for t in amb if f"{rel}:{t}" not in accepted]

    seen = {f"{h['file']}:{t}" for h in result["ambiguous_hits"] for t in h["tokens"]}
    unused = sorted(set(accepted) - seen)
    if unused:
        result["ambiguous_accept_unused"] = unused

    result["clean"] = (not result["hits"] and not result["ambiguous_unresolved"]
                       and not result["unreadable"])
    # A sweep that examined nothing is never a pass — that shape has produced a
    # false all-clear before (an empty list plus a loop that silently ran zero times).
    if result["scanned"] == 0:
        result["clean"] = False
        result["error"] = "scanned 0 files — an empty sweep is not a pass"
    elif result["unreadable"] and not result["hits"]:
        result["error"] = (f"{len(result['unreadable'])} public file(s) could not be "
                           "read and were not checked; see unreadable[]")
    elif result["ambiguous_unresolved"] and not result["hits"]:
        result["error"] = (
            "ambiguous-tier match(es) with no verdict. Each token is a pipeline "
            "company name that is also an ordinary word. Open each file at the "
            "lines given; replace a real reference with a placeholder, and pass "
            "--accept-ambiguous FILE:TOKEN for each one that is not the company.")

    print(json.dumps(result, indent=2))
    if result["hits"]:
        return 2
    if result["scanned"] == 0 or result["unreadable"]:
        return 1
    return 3 if result["ambiguous_unresolved"] else 0


# --- `cd` inside a Bash command ----------------------------------------------
# WHY THIS EXISTS: a relative write target was resolved against the session cwd even
# when the command began `cd some/dir && ...`. Two wrong answers followed. A write to a
# gitignored folder was read as a root-level public file and blocked (4 logged fires,
# 2026-08-20 to 2026-10-13, the last on `cd output/... && for f in ...; do ... >
# sub/$f.json; done`). And `cd tools && echo NAME > data/x.py` was read as the private
# `data/x.py` and ALLOWED while bash wrote the public `tools/data/x.py`.
#
# The rule is fail-closed. A `cd` moves the tracked cwd EXCLUSIVELY only when all hold:
#   - it is a whole top-level segment `cd DIR` (options -L and -P allowed), literal DIR;
#   - it is reached unconditionally (first, or after `;` / newline only);
#   - DIR exists and is searchable, so the cd cannot fail;
#   - nothing else in the command can change a working directory (see _CWD_CHANGERS).
# When a pure cd fails any other condition, the old directory stays a candidate
# alongside the new one, and a target that is public from ANY candidate is judged. A cd
# that is not pure (a variable operand, a subshell, an unknown option) adds no candidate:
# the directories already held stay, so the hook is no weaker there than before cd
# tracking existed. Nothing that was blocked before is allowed now unless the command
# can only have written somewhere else.

# Any other way a cwd can change, anywhere in the raw text (nested `bash -c` strings and
# heredoc scripts included): another cd/pushd/popd, code the hook cannot read (eval,
# source, `.`), and tool flags that run a child elsewhere (`env -C`, `tee` under
# `sudo -D`, `--chdir`). One match more than the pure top-level cds found ends exclusive
# tracking for the whole command.
_CWD_CHANGERS = re.compile(
    r"(?<![\w./-])(?:cd|pushd|popd|eval|source)(?![\w./-])"
    r"|(?:^|[;&|({'\"`\n]\s*|\b(?:then|do|else)\s+)\.\s"
    r"|(?<!\S)(?:-C|-D|--chdir|--directory|--cwd)(?![\w-])")
_CD_OPERAND_UNSAFE = re.compile(r"[$`*?\[\]{}~\\]")


_CD_OPTION = re.compile(r"-[LP]+")


def pure_cd_operand(segment: str) -> str | None:
    """DIR when the segment is exactly `cd [-L|-P]... [--] DIR` with a literal DIR.

    Every token must be a plain word: a trailing `&` (background subshell), a pipe, a
    redirect or a group paren means the cd does not move the shell that runs the next
    segment. The options move bash exactly as a plain `cd DIR` does (`-P` changes how
    `..` reads, and apply_cd keeps both readings anyway); before they were accepted,
    `cd -P tools; echo NAME > data/x.py` was not tracked at all (Codex review,
    2026-10-13). Any other option returns None: `-e` and `-@` are rejected by macOS
    bash 3.2 and zsh, so the cd fails and the shell stays where it was (tested
    2026-10-13; accepting them briefly made `cd -e output; echo NAME > notes.md` pass).
    Known gaps, no worse than before tracking existed: `cd -- -P` (a directory named
    like an option) and `cd -` are not tracked.
    """
    operand = cd_operand_text(segment)
    # `+N` is zsh's directory stack, not a folder named `+N` (Codex review, 2026-10-13).
    if not operand or operand[0] in "-+" or _CD_OPERAND_UNSAFE.search(operand):
        return None
    return operand


def cd_operand_text(segment: str) -> str | None:
    """The operand of a `cd [-L|-P]... [--] WORD` segment as written, `$dir` unexpanded.

    None for any other shape. pure_cd_operand narrows this to a literal directory; the
    Bash branch also expands a variable operand the command assigns (see main).
    """
    parts = cd_parts(segment)
    return parts[1] if parts else None


def cd_parts(segment: str) -> tuple[list[str], str] | None:
    """(options, operand) of a `cd [-L|-P]... [--] WORD` segment, else None."""
    toks = tokenize(segment)
    if not toks or any(t.kind != "word" or t.subs for t in toks):
        return None
    if toks[0].text != "cd" or toks[0].quoted:
        return None
    rest = [t.text for t in toks[1:]]
    opts = []
    while rest and _CD_OPTION.fullmatch(rest[0]):
        opts.append(rest.pop(0))
    if rest[:1] == ["--"]:
        rest = rest[1:]
    if len(rest) != 1:
        return None
    return opts, rest[0]


# Shell startup state the hook cannot see in the command: a search path (`cdpath` in
# zsh, CDPATH in bash), a `cd` alias or function, or a chpwd hook sends `cd sub`
# somewhere else. zsh with `cdpath=(tools .)` runs `cd sub` into tools/sub even when sub/
# exists (Codex review, 2026-10-13). Claude Code runs each Bash call as
# `zsh -c 'source <snapshot> ... && eval <command>'`, a non-login, non-interactive shell,
# so the state is the snapshot plus the zshenv files zsh always reads.
#
# The hook ASKS the shell rather than reading those files as text. Two rounds of
# pattern-matching lost to spellings the shell accepts (`alias c'd'=z`,
# `builtin . file`) and fired on text that changes nothing (`# source ...`), which
# restored the very false block tracking removes (Codex review, 2026-10-13). No answer
# means unknown, which ends exact tracking: the old directory stays a candidate, as before tracking existed.
#
# Fidelity (Codex review, 2026-10-13, three rounds): the probe command has the shape
# Claude Code runs, `<zsh> -c 'source <snapshot> ...'` with the path written into the
# command text and no positional parameters ($# and $1 are visible to startup code); zsh
# reads /etc/zshenv and $ZDOTDIR/.zshenv itself, in its own order; the shell is named by
# absolute path, and when $SHELL names a different one than /bin/<shell> both are asked.
# There is NO cache: startup code can branch on the inherited environment, so no key
# short of rerunning it says the answer still holds. The cost is one probe per Bash call
# that contains a pure cd (see cwd_tracking_is_exact), about 30 ms.
# After the three questions the probe runs the COMMAND'S OWN cds, from each directory
# the session can start in, and reports where each landed (see _cd_trial). That catches
# what the questions miss: a restricted shell (`setopt restricted`, `set -r`) answers
# them clean while every cd fails, and startup code can branch on the directory it
# starts in (`[[ $PWD == */repo ]] && cdpath=(tools .)`), so a trial from any other
# directory proves nothing (Codex review, 2026-10-13, two rounds).
_ZSH_QUERY = (
    'builtin print -r -- "W=$(builtin whence -w cd)"\n'
    'builtin print -r -- "P=${(j: :)cdpath}:${CDPATH-}"\n'
    'builtin print -r -- "H=${+functions[chpwd]}:${(j: :)chpwd_functions}"\n')
_ZSH_LANDED = 'builtin print -r -- "X=$(builtin pwd -P)"\n'
_ZSH_CLEAN = "W=cd: builtin\nP=:\nH=0:"
# bash reads $BASH_ENV by itself. expand_aliases is on so a `cd` alias counts whether
# or not the snapshot enables it.
_BASH_QUERY = ('builtin echo "W=$(builtin type -t cd)"\n'
               'builtin echo "P=${CDPATH-}"\n')
_BASH_LANDED = 'builtin echo "X=$(builtin pwd -P)"\n'
_BASH_CLEAN = "W=builtin\nP="
_SHELL_PROBE_TIMEOUT_S = 5


def _sh_quote(text: str) -> str:
    """`text` as one single-quoted word for zsh and bash."""
    return "'" + text.replace("'", "'\\''") + "'"


def _shell_paths(name: str) -> list[str]:
    """Every absolute path the shell could be run from: /bin/<name>, plus $SHELL when
    it is that shell somewhere else. Never a PATH lookup, which another `zsh` could
    answer."""
    paths = [f"/bin/{name}"]
    sh = os.environ.get("SHELL", "")
    if os.path.isabs(sh) and os.path.basename(sh) == name and sh not in paths:
        paths.append(sh)
    return paths


def _shell_state_parts() -> tuple[str, list[str], list[str], list[str]]:
    """(home, snapshots, zshenv files, BASH_ENV files) for the shell a Bash call runs in.

    PII_SHELL_STATE_HOME stands in for $HOME so tests never read the tester's own
    config. zsh itself decides which zshenv it reads; the list says whether a zsh with
    no snapshot is worth asking at all.
    """
    fake = os.environ.get("PII_SHELL_STATE_HOME")
    home = fake or os.path.expanduser("~")
    snaps = sorted(glob.glob(os.path.join(home, ".claude", "shell-snapshots", "*.sh")))
    zdot = os.environ.get("ZDOTDIR") or home
    zshenv = ["/etc/zshenv", os.path.join(zdot, ".zshenv")]
    bash_env = [os.environ["BASH_ENV"]] if os.environ.get("BASH_ENV") else []
    return home, snaps, zshenv, bash_env


def shell_state_files() -> list[str]:
    """Every file whose contents shape the shell a Bash call runs in."""
    _, snaps, zshenv, bash_env = _shell_state_parts()
    return snaps + zshenv + bash_env


def _cd_trial(cd_segments: list[str], landed: str) -> str:
    """Shell lines that run the command's own pure cds, each followed by `landed`."""
    lines = []
    for seg in cd_segments:
        opts, operand = cd_parts(seg)
        lines.append(" ".join(["cd", *opts, "--", _sh_quote(operand)]) + " >/dev/null 2>&1\n")
        lines.append(landed)
    return "".join(lines)


def _shell_probes(cd_segments: list[str]) -> list[tuple[list[str], str, dict[str, str]]]:
    """(argv, the answer a shell that leaves cd alone gives before its X= lines, env)
    per shell to ask. Each runs `cd_segments` after the questions."""
    home, snaps, zshenv, _ = _shell_state_parts()
    env = {**os.environ, "HOME": home}
    zsh_snaps = [f for f in snaps if os.path.basename(f).startswith("snapshot-zsh")]
    probes = []
    if zsh_snaps or any(os.path.exists(f) for f in zshenv):
        trial = _ZSH_QUERY + _cd_trial(cd_segments, _ZSH_LANDED)
        for snap in zsh_snaps or [""]:
            load = f"source {_sh_quote(snap)} >/dev/null 2>&1 || true\n" if snap else ""
            for zsh in _shell_paths("zsh"):
                probes.append(([zsh, "-c", load + trial], _ZSH_CLEAN, env))
    trial = _BASH_QUERY + _cd_trial(cd_segments, _BASH_LANDED)
    for snap in snaps:
        if snap not in zsh_snaps:
            load = ("shopt -s expand_aliases\n"
                    f"source {_sh_quote(snap)} >/dev/null 2>&1 || true\n")
            for bash in _shell_paths("bash"):
                probes.append(([bash, "--norc", "--noprofile", "-c", load + trial],
                               _BASH_CLEAN, env))
    return probes


def _expected_landings(start: str, cd_segments: list[str]) -> list[set[str]]:
    """For each cd in turn, the physical directories the model says it can land in:
    the typed and the on-disk reading of every directory the previous cd could reach
    (the same two readings apply_cd keeps)."""
    cur, out = [start], []
    for seg in cd_segments:
        _, operand = cd_parts(seg)
        nxt = []
        for c in cur:
            joined = operand if os.path.isabs(operand) else os.path.join(c, operand)
            nxt += [os.path.normpath(joined), os.path.realpath(joined)]
        cur = list(dict.fromkeys(nxt))
        out.append({os.path.realpath(d) for d in cur})
    return out


def shell_may_redirect_cd(starts: list[str], cd_segments: list[str]) -> bool:
    """True unless every shell a Bash call can run in, started in every directory the
    session can be in, answers the questions clean and lands each of the command's
    cds where the model expects.

    A shell that fails to answer is unknown, and unknown is True.
    """
    probes = _shell_probes(cd_segments)
    if not probes:
        return False
    try:
        for start in starts:
            expected = _expected_landings(start, cd_segments)
            for argv, clean, env in probes:
                r = subprocess.run(argv, capture_output=True, text=True,
                                   env={**env, "PWD": start}, cwd=start,
                                   stdin=subprocess.DEVNULL,
                                   timeout=_SHELL_PROBE_TIMEOUT_S)
                lines = r.stdout.strip().splitlines()
                n = len(clean.splitlines())
                if "\n".join(lines[:n]) != clean or len(lines) != n + len(expected):
                    return True
                for line, allowed in zip(lines[n:], expected):
                    if not line.startswith("X=") or line[2:] not in allowed:
                        return True
    except (OSError, subprocess.SubprocessError):
        return True
    return False


def cwd_tracking_is_exact(command: str, pairs: list[tuple[str, frozenset[str]]],
                          starts: list[str] | None = None) -> bool:
    """True when the command's only cwd changes are its pure top-level `cd DIR` segments
    and the shell, started where the session is (`starts`), runs them as modeled."""
    # zsh's search path is the lowercase array `cdpath` (Codex review, 2026-10-13).
    if "cdpath" in command.lower() or os.environ.get("CDPATH"):
        return False                # `cd rel` may then land somewhere else entirely
    cds = [text.strip() for text, _ in pairs if pure_cd_operand(text) is not None]
    if len(_CWD_CHANGERS.findall(command)) != len(cds):
        return False
    # Asked last, and only when there is a cd to trust: it starts a shell.
    return not cds or not shell_may_redirect_cd(
        starts or [os.path.realpath(os.getcwd())], cds)


def apply_cd(cwds: list[str], operand: str, certain: bool) -> list[str]:
    """The candidate working directories after `cd operand`.

    `certain` means the cd is known to run. It replaces the candidates only when it
    also cannot fail: every directory it could land in exists and is searchable.
    Otherwise old and new are both kept.

    `..` after a symlink has two readings. bash resolves it on the path as typed
    (`tools/link/..` is `tools/`), and under `set -P` or `cd -P` on the disk (`..` of
    whatever the link points at). Both are kept as candidates, so neither a default
    shell nor a physical one can write somewhere this did not judge. The typed reading
    is kept unresolved, so a LATER separate `cd ..` still sees the link: after
    `cd tools/link; cd ..` bash is in tools/ (Codex review, 2026-10-13).
    """
    new: list[str] = []
    settled = certain
    for c in cwds:
        joined = operand if os.path.isabs(operand) else os.path.join(c, operand)
        # The shell walks the operand as typed, so `output/missing/..` fails even though
        # it simplifies to an existing `output` (Codex review, 2026-10-13).
        if not os.path.isdir(joined):
            settled = False
        for d in (os.path.normpath(joined), os.path.realpath(joined)):
            if not (os.path.isdir(d) and os.access(d, os.X_OK)):
                settled = False
            new.append(d)
    new = list(dict.fromkeys(new))
    return new if settled else list(dict.fromkeys(cwds + new))


def start_cwds(typed: list[str]) -> list[str]:
    """The directories a command starts in: the one on disk, plus its typed spelling.

    getcwd() is the resolved path. A shell that entered through a symlink also holds the
    path as typed, and its `cd ..` follows that one (from docs/alias -> .. it lands in
    docs/, not above the repo). Each typed spelling (the payload's `cwd`, $PWD) is kept
    only when it is absolute and resolves to this same directory, so a stale one adds
    nothing (Codex review, 2026-10-13).
    """
    here = os.path.realpath(os.getcwd())
    out = [here]
    for t in typed:
        if t and os.path.isabs(t) and os.path.realpath(t) == here:
            out.append(os.path.normpath(t))
    return list(dict.fromkeys(out))


def resolve_public_targets(candidates: list[str], root: Path,
                           skip_binary: bool = True,
                           cwds: list[str] | None = None) -> list[str]:
    """Repo-relative paths from `candidates` that actually ship to the public remote.

    A relative target resolves against the hook process cwd, which is the session cwd,
    unless `cwds` is given: the Bash branch passes every directory the command could be
    in when the write happens (see apply_cd), and a target public from ANY of them is
    returned. A path that falls outside the repo is skipped -- fail open, never a false
    block.
    """
    out = []
    for cand in candidates:
        if not cand:
            continue
        if cwds is None or os.path.isabs(cand):
            paths = [cand]
        else:
            paths = [os.path.join(c, cand) for c in cwds]
        for path in paths:
            try:
                # realpath, not abspath: a repo reached through a symlink resolved to a
                # path 'outside the repo' and failed open (2026-08-19).
                rel = os.path.relpath(os.path.realpath(path), os.path.realpath(root))
            except Exception:
                continue
            if rel.startswith(".."):  # outside the repo
                continue
            rel = rel.replace(os.sep, "/")
            if not is_public_path(rel, root) or is_gitignored(root, rel):
                continue
            # The binary skip exists because a PDF's BYTE STREAM false-positives. On the
            # Bash path the scanned text is the COMMAND, not the file, so the extension is
            # irrelevant -- and skipping let `echo TOKEN > docs/leak.pdf` write a plain-text
            # name into a tracked file unchecked (2026-08-19).
            if skip_binary and is_binary(rel):
                continue
            if rel not in out:
                out.append(rel)
    return out


def judge(content: str, public_targets: list[str], root: Path) -> None:
    """WARN or BLOCK on `content` headed for `public_targets`. Exits 2 to block.

    Shared by the Write/Edit and Bash paths so the two can never drift -- a drifted
    copy is what caused the 4th/5th fires in the command-hook family (HOOK_AUTHORING).
    """
    if not public_targets:
        return

    tokens = load_denylist(root)
    if not tokens:
        return  # fail open — no denylist, nothing to enforce

    hits = find_pii(content, tokens) + find_target_words(content, load_target_words(root))
    names = ", ".join(Path(t).name for t in public_targets)

    # WARN tier (added 2026-08-10). Single-token company names that are also ordinary
    # English words are excluded from the BLOCK list above, because matching them would
    # false-positive on prose. Excluding them entirely is what let a live pipeline
    # company reach six public files while every one of its contacts
    # was correctly blocked. So: surface, never block. Per feedback_warn_vs_block_hook_design.
    amb_hits = find_pii(content, load_ambiguous(root))
    if amb_hits and not hits:
        uniq_amb = sorted(set(amb_hits))
        print(
            f"WARN: {names} contains token(s) that match a pipeline company "
            f"name which is also an ordinary word: {', '.join(uniq_amb)}.\n"
            "Not blocking — this is very often a false positive. But if any of these refers "
            "to the real company, replace it with a placeholder (ActiveCo / ClosedCo / Acme) "
            "before committing. Ambiguous tier: tools/.pii-denylist-ambiguous.txt",
            file=sys.stderr,
        )

    if not hits:
        return

    uniq = sorted(set(hits))
    msg = [
        f"BLOCKED: {names} is a public-repo artifact and the content contains real PII.",
        "",
        f"Matched denylisted token(s): {', '.join(uniq)}",
        "",
        "The job-search OS repo is PUBLIC. Real contacts and pipeline/target companies",
        "must never appear in tests, skill docs, framework docs, or tool comments.",
        "",
        "Fix: replace each with a generic placeholder that preserves the example's intent",
        "(people: Casey Doe / Jordan Sample / Alex Example; companies: ClosedCo / ActiveCo /",
        "LiveCo / Acme). Keep only the keyword the logic actually tests.",
        "",
        "Rule: feedback_generalize_examples_in_public_artifacts. If this is a false positive",
        "(the token is genuinely generic here), log it:",
        f"  PYTHONIOENCODING=utf-8 python3 tools/friction_log.py append check_public_pii.py \"FP: {uniq[0]}\"",
    ]
    print("\n".join(msg), file=sys.stderr)
    sys.exit(2)


def main():
    # --scan <paths...> | --scan --stdin-paths : sweep mode (NOT the hook path).
    argv = sys.argv[1:]
    if argv and argv[0] == "--scan":
        rest, accepted, bad = parse_scan_args(argv[1:])
        if bad:
            print(bad, file=sys.stderr)
            sys.exit(2)
        paths = rest or [ln.strip() for ln in sys.stdin.read().splitlines() if ln.strip()]
        # The sweep fails CLOSED. The handler at the bottom of this file turns any
        # exception into exit 0, which is right for the hook (never break a session) and
        # wrong here: an undecodable tier file raised before one path was opened and the
        # sweep "passed" (2026-10-13).
        try:
            code = scan_paths(paths, accepted)
        except Exception as exc:
            print(json.dumps({"clean": False, "scanned": 0,
                              "error": f"sweep did not run: {type(exc).__name__}: {exc}"},
                             indent=2))
            code = 1
        sys.exit(code)

    # AN UNRECOGNISED ARGUMENT IS AN ERROR, NOT A FALL-THROUGH.
    #
    # Without this, anything that is not exactly "--scan" dropped into the hook path
    # below and blocked on json.load(sys.stdin). Invoked from a shell with no stdin --
    # a backgrounded task, a launchd job, a `&` -- that read never returns.
    #
    # Measured 2026-09-06: `check_public_pii.py --paths <files>` (the flag is --scan;
    # --paths does not exist) sat for 3 hours 53 minutes at 0.00% CPU, holding nothing,
    # producing nothing. The background task it belonged to reported its earlier steps
    # and then simply stopped, so the PII sweep it was meant to perform silently never
    # ran and nothing said so.
    #
    # A hook that hangs on a typo is worse than one that rejects it: the caller gets no
    # exit code, no message, and no reason to look. sibling guard
    # check_scanner_examined_something.py catches this shape for hook-only scripts that
    # declare no flags at all; this one HAS a flag, so it fell through the gap between
    # them.
    if argv:
        print(f"unknown argument {argv[0]!r}. Sweep mode is:\n"
              f"  python3 tools/check_public_pii.py --scan <path>...\n"
              f"  python3 tools/check_public_pii.py --scan --stdin-paths  "
              f"(paths on stdin)\n"
              f"With no arguments this script is a PreToolUse hook and reads a JSON "
              f"payload on stdin.", file=sys.stderr)
        sys.exit(2)

    p = read_payload()
    if p.truncated:
        # FAIL CLOSED. Truncation means this guard could not see the content it exists
        # to inspect, which is NOT the same as the producer sending garbage. Failing
        # open here is a silent bypass of the public-repo PII gate: write a payload
        # above the read ceiling and the check passes without reading a byte of it.
        # A large file write is an ordinary event, not an exotic one.
        # Origin: 2026-09-14 cross-model verification F1.
        sys.stderr.write(
            "BLOCKED: the hook payload was truncated at a stdin read bound, so the "
            "public-repo PII gate could not inspect this write.\n"
            "This fails CLOSED by design. Re-run the write, or scan the file directly:\n"
            "  PYTHONIOENCODING=utf-8 python3 tools/check_public_pii.py --scan <path>\n"
        )
        sys.exit(2)
    if not p.ok:
        return
    data = p.data

    tool_name = data.get("tool_name", "")
    tool_input = data.get("tool_input", {}) or {}

    root = repo_root()

    # What is about to land, and in which file(s)?
    #   Write/Edit -> one declared file_path; content comes from the payload.
    #   Bash       -> targets parsed out of the command, per segment, with the
    #                 segment text ITSELF as the content (heredoc bodies included).
    #                 Added 2026-08-18: Bash was outside the matcher entirely, so
    #                 every heredoc write to a public file skipped this gate.
    if tool_name == "Write":
        judge(tool_input.get("content", ""),
              resolve_public_targets([tool_input.get("file_path", "")], root), root)
    elif tool_name == "Edit":
        judge(tool_input.get("new_string", ""),
              resolve_public_targets([tool_input.get("file_path", "")], root), root)
    elif tool_name == "MultiEdit":
        # Ungated until 2026-08-19: MultiEdit is a routine write path and was in
        # NEITHER the matcher nor this dispatch, so every edit through it skipped the
        # gate entirely. Each edit's new_string is scanned; old_string is not, since
        # that text is being removed (same rule as the Edit branch).
        edits = tool_input.get("edits") or []
        content = "\n".join(e.get("new_string", "") for e in edits if isinstance(e, dict))
        judge(content, resolve_public_targets([tool_input.get("file_path", "")], root), root)
    elif tool_name == "NotebookEdit":
        judge(tool_input.get("new_source", ""),
              resolve_public_targets([tool_input.get("notebook_path", "")], root), root)
    elif tool_name == "Bash":
        command = tool_input.get("command", "")
        # Assignments in one segment reach the next (`OUT=docs/f; echo x > "$OUT"`).
        env = command_assignments(command)
        pairs = segments_with_separators(command)
        cwds = start_cwds([str(data.get("cwd") or ""), os.environ.get("PWD", "")])
        exact = cwd_tracking_is_exact(command, pairs, cwds)
        for segment, before in pairs:
            operand = pure_cd_operand(segment)
            if operand is not None:
                cwds = apply_cd(cwds, operand,
                                certain=exact and before <= {";", "\n"})
                continue                                # a bare cd writes nothing
            # `dir=tools; cd "$dir"` moves the shell to every value the command gives
            # dir. Each is ADDED (never certain), so the old directories stay. HEAD
            # allowed `... > data/x.py` there (Codex review, 2026-10-13). A variable the
            # command does not assign adds nothing, as before tracking existed.
            text = cd_operand_text(segment)
            if text is not None and _VAR_REF.search(text):
                for value in _expand_vars(text, env):
                    if (value and value[0] not in "-+"
                            and not _CD_OPERAND_UNSAFE.search(value)):
                        cwds = apply_cd(cwds, value, certain=False)
                continue
            # When tracking is not exact no cd is `certain`, so apply_cd only ever adds
            # candidates and the session cwd is still among them, as before this existed.
            targets = resolve_public_targets(extract_write_targets(segment, env), root,
                                             skip_binary=False, cwds=cwds)
            if targets:
                # The content a segment writes includes the values of variables it
                # references: in `c='echo NAME > docs/f'; eval "$c"` the name lives
                # in the assignment segment (Codex coverage run 2026-10-01, 4th).
                held = [v for m in _VAR_REF.finditer(segment)
                        for v in env.get(m.group(1) or m.group(4) or "", [])]
                judge("\n".join([strip_sed_search_sides(segment)] + held), targets, root)
    return


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception as e:
        print(f"check_public_pii.py error (allowing through): {e}", file=sys.stderr)
